export function calculateWordSum(word: string): number {
  return word
    .toLowerCase()
    .replace(/[^a-z]/g, '')
    .split('')
    .reduce((sum, char) => sum + (char.charCodeAt(0) - 96), 0)
}

export function getWordBreakdown(word: string): string {
  const letters = word.toLowerCase().replace(/[^a-z]/g, '').split('')
  const parts = letters.map(c => `${c.toUpperCase()}(${c.charCodeAt(0) - 96})`)
  const total = calculateWordSum(word)
  return `${parts.join(' + ')} = ${total}`
}

